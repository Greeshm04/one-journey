export function t(lang, key, ...args) {
  const val = translations[lang]?.[key] ?? translations['en']?.[key] ?? key;
  return typeof val === 'function' ? val(...args) : val;
}

/** Translated duration formatter — replaces the raw fmt() for display */
export function fmtDuration(lang, totalMinutes) {
  const m = Math.round(totalMinutes);
  if (m < 60) {
    return t(lang, 'fmtMin', m);
  }
  const h = Math.floor(m / 60);
  const rem = m % 60;
  return t(lang, 'fmtHour', h, rem);
}

/** Translate a leg type key to its display label */
export function legLabel(lang, typeKey) {
  const map = { walk: 'legWalk', metro: 'legMetro', brts: 'legBRTS', gtsl: 'legGTSL', amts: 'legAMTS' };
  return t(lang, map[typeKey] ?? typeKey);
}
